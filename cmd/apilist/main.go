// Command apilist regenerates api.txt: the public surface of
// github.com/laenen-ai/iam as a golden file, which CHARTER.md requires be
// diffed in CI so that growing the surface takes a reviewed diff.
//
// It lists every exported declaration of the root package — the facade —
// with its signature and nothing else: no doc comments, no bodies. That
// choice is what makes the file useful as a gate. A golden file containing
// the doc comments would churn on every wording change and train reviewers
// to approve its diffs unread; a file containing only names and types
// changes exactly when an identifier is added, removed or retyped, which
// is the event the charter wants seen.
//
// It is also the reachability check CONVENTIONS asks for: if a consumer
// would need to name something, it belongs in this file. A constructor
// missing here is a constructor a consumer outside the module cannot call,
// which is how `audit` shipped a facade that hid what the module was for.
//
// Run it through `mise run api`; `mise run api-check` runs it and then
// fails if the working tree differs.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// outputPath is where the golden file lives, relative to the module root.
const outputPath = "api.txt"

// header is prepended so nobody hand-edits the file.
const header = "# Public API of github.com/laenen-ai/iam.\n" +
	"# Generated by `mise run api` (cmd/apilist). Do not edit by hand.\n" +
	"#\n" +
	"# CHARTER.md: this file is the public API as a golden file, diffed in CI,\n" +
	"# so growing the surface takes a reviewed diff. If a consumer would need to\n" +
	"# name an identifier, it must appear here.\n"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "apilist:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}

	// The root package only: api.txt is the facade's surface, and
	// internal/ packages are not reachable from another module by
	// definition. The files are read individually rather than through
	// parser.ParseDir, which is deprecated, and without
	// golang.org/x/tools/go/packages, which would be a dependency for one
	// directory listing.
	entries, err := os.ReadDir(root)
	if err != nil {
		return fmt.Errorf("read %s: %w", root, err)
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)

	fset := token.NewFileSet()
	var lines []string
	for _, name := range names {
		file, err := parser.ParseFile(fset, filepath.Join(root, name), nil, 0)
		if err != nil {
			return fmt.Errorf("parse %s: %w", name, err)
		}
		lines = append(lines, declarations(fset, file)...)
	}
	sort.Strings(lines)

	out := header
	for _, l := range lines {
		out += l + "\n"
	}
	return os.WriteFile(filepath.Join(root, outputPath), []byte(out), 0o644) //nolint:gosec // a generated, committed, world-readable golden file
}

// declarations renders one source file's exported declarations, one line
// each, in a stable form.
func declarations(fset *token.FileSet, file *ast.File) []string {
	var out []string
	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if !d.Name.IsExported() || d.Recv != nil {
				// Methods are rendered with their receiver's type, so a
				// top-level pass over funcs only needs free functions.
				continue
			}
			// printer renders an ast.FuncType with its own leading
			// "func" keyword, so strip it before splicing the name in.
			sig := strings.TrimPrefix(render(fset, funcSignature(d)), "func")
			out = append(out, "func "+d.Name.Name+sig)
		case *ast.GenDecl:
			out = append(out, genDeclarations(fset, d)...)
		}
	}
	return out
}

// genDeclarations renders the exported specs of a const, var or type
// declaration. Each spec becomes its own line regardless of whether the
// source grouped them, so regrouping a block does not show up as a diff in
// the public surface.
func genDeclarations(fset *token.FileSet, d *ast.GenDecl) []string {
	var out []string
	for _, spec := range d.Specs {
		switch s := spec.(type) {
		case *ast.TypeSpec:
			if !s.Name.IsExported() {
				continue
			}
			kind := "type " + s.Name.Name
			if s.Assign.IsValid() {
				// A type alias. The distinction is the whole point of the
				// facade — an alias makes a consumer's value and this
				// module's value the identical type — so it must be
				// visible in the golden file.
				out = append(out, kind+" = "+render(fset, s.Type))
				continue
			}
			out = append(out, kind+" "+render(fset, s.Type))
		case *ast.ValueSpec:
			keyword := "const"
			if d.Tok == token.VAR {
				keyword = "var"
			}
			for i, name := range s.Names {
				if !name.IsExported() {
					continue
				}
				line := keyword + " " + name.Name
				if s.Type != nil {
					line += " " + render(fset, s.Type)
				}
				if i < len(s.Values) {
					line += " = " + render(fset, s.Values[i])
				}
				out = append(out, line)
			}
		}
	}
	return out
}

// funcSignature strips a function declaration down to its type, so the
// rendered line carries the parameters and results and not the body.
func funcSignature(d *ast.FuncDecl) ast.Expr {
	return &ast.FuncType{Params: d.Type.Params, Results: d.Type.Results, TypeParams: d.Type.TypeParams}
}

// render prints an AST node in gofmt form on a single line.
func render(fset *token.FileSet, node ast.Node) string {
	var b strings.Builder
	cfg := printer.Config{Mode: printer.RawFormat, Tabwidth: 8}
	if err := cfg.Fprint(&b, fset, node); err != nil {
		// Unreachable for a node that parsed; rendering it as an explicit
		// marker is still better than dropping the identifier silently,
		// since a missing line in this file is a missing review.
		return "<unprintable>"
	}
	// A struct or interface type spans lines; collapse it so one
	// declaration is one line and the file sorts stably.
	return strings.Join(strings.Fields(b.String()), " ")
}

// moduleRoot returns the directory holding go.mod, walking up from the
// working directory so the command works from anywhere in the module.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod found above %s", dir)
		}
		dir = parent
	}
}
