// changeClearanceMembership is the one path into a clearance group's
// membership, shared by the add and remove methods so neither can acquire
// a weaker precondition than the other. The membership write and its trail
// entry are one transaction: a clearance that is held with no record of
// who granted it is the failure design §8.3's audit requirement exists to
// prevent.
func (r *Registry) changeClearanceMembership(ctx context.Context, act domain.MandatoryAct, g domain.ClearanceGroupID, p domain.PrincipalID, kind domain.ClearanceChangeKind) error {
	if err := registry.RequireMandatoryAct(act); err != nil {
		return err
	}
	return r.inTx(ctx, func(tx pgx.Tx) error {
		cg, err := r.requireClearanceGroup(ctx, tx, g)
		if err != nil {
			return err
		}
		if cg.Channel != act.Channel() {
			return registry.ChannelMismatchError(cg, act)
		}
		principal, err := r.principal(ctx, tx, p)
		if err != nil {
			return err
		}
		if kind == domain.ClearanceChangeAdded && !principal.DeprovisionedAt.IsZero() {
			return fmt.Errorf("%w: %s", domain.ErrPrincipalDeprovisioned, p)
		}

		switch kind {
		case domain.ClearanceChangeAdded:
			const add = `
				INSERT INTO iam.clearance_group_members
					(clearance_group_id, principal_id, channel, actor_principal_id, reason, acted_at)
				VALUES ($1, $2, $3, $4, $5, $6)
				ON CONFLICT (principal_id, clearance_group_id) DO UPDATE SET
					channel = EXCLUDED.channel,
					actor_principal_id = EXCLUDED.actor_principal_id,
					reason = EXCLUDED.reason,
					acted_at = EXCLUDED.acted_at`
			if _, err := tx.Exec(ctx, add, cg.ID.String(), string(p),
				string(act.Channel()), string(act.Actor()), act.Reason(), act.At()); err != nil {
				return mapErr(err)
			}
		case domain.ClearanceChangeRemoved:
			const del = `DELETE FROM iam.clearance_group_members
				WHERE clearance_group_id = $1 AND principal_id = $2`
			if _, err := tx.Exec(ctx, del, cg.ID.String(), string(p)); err != nil {
				return mapErr(err)
			}
		case domain.ClearanceChangeCreated:
			return fmt.Errorf("%w: creation is recorded by EnsureClearanceGroup", domain.ErrConflict)
		}

		// Recorded even when the membership did not change: "someone
		// re-asserted this clearance, and why" is itself the audit
		// record, and so is a withdrawal of a clearance not held.
		return r.record(ctx, tx, cg.ID, p, kind, act)
	})
}

// record appends one entry to a clearance group's trail. Nothing in this
// package updates or deletes one, and the table refuses to be edited
// anyway (see the append-only trigger in 00002_identity.sql).
func (r *Registry) record(ctx context.Context, q querier, g domain.ClearanceGroupID, p domain.PrincipalID, kind domain.ClearanceChangeKind, act domain.MandatoryAct) error {
	var principal *string
	if p != "" {
		s := string(p)
		principal = &s
	}
	const sql = `
		INSERT INTO iam.clearance_group_changes
			(id, clearance_group_id, principal_id, kind, channel, actor_principal_id, reason, acted_at, recorded_at)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)`
	_, err := q.Exec(ctx, sql,
		string(domain.NewChangeID(r.cfg.Clock)), g.String(), principal, string(kind),
		string(act.Channel()), string(act.Actor()), act.Reason(), act.At(), r.cfg.Clock.Now())
	return mapErr(err)
}

// ClearanceGroupsOf implements registry.Registry.
func (r *Registry) ClearanceGroupsOf(ctx context.Context, p domain.PrincipalID, asOf time.Time) ([]domain.ClearanceGroup, error) {
	if _, err := r.usable(ctx, r.pool, p, asOf); err != nil {
		return nil, err
	}
	const sql = `
		SELECT cg.id, cg.tenant_id, cg.name, cg.channel, cg.created_at
		FROM iam.clearance_group_members m
		JOIN iam.clearance_groups cg ON cg.id = m.clearance_group_id
		WHERE m.principal_id = $1
		ORDER BY cg.name, cg.id`
	rows, err := r.pool.Query(ctx, sql, string(p))
	if err != nil {
		return nil, mapErr(err)
	}
	defer rows.Close()

	var out []domain.ClearanceGroup
	for rows.Next() {
		cg, err := scanClearanceGroup(rows)
		if err != nil {
			return nil, mapErr(err)
		}
		out = append(out, cg)
	}
	if err := rows.Err(); err != nil {
		return nil, mapErr(err)
	}
	return out, nil
}

// ClearanceGroupMembers implements registry.Registry.
func (r *Registry) ClearanceGroupMembers(ctx context.Context, g domain.ClearanceGroupID, asOf time.Time) ([]domain.PrincipalID, error) {
	cg, err := r.requireClearanceGroup(ctx, r.pool, g)
	if err != nil {
		return nil, err
	}
	const sql = `
		SELECT ` + principalColumns + `
		FROM iam.clearance_group_members m
		JOIN iam.principals p ON p.id = m.principal_id
		WHERE m.clearance_group_id = $1
		ORDER BY p.id`
	return r.usableMembers(ctx, sql, cg.ID.String(), asOf)
}

// ClearanceGroupChanges implements registry.Registry.
//
// Ordered by seq, not by id: two ULIDs minted inside the same millisecond
// do not sort by creation time, so "recorded order" needs the table's own
// monotonic column.
func (r *Registry) ClearanceGroupChanges(ctx context.Context, g domain.ClearanceGroupID) ([]domain.ClearanceChange, error) {
	cg, err := r.requireClearanceGroup(ctx, r.pool, g)
	if err != nil {
		return nil, err
	}
	const sql = `
		SELECT id, principal_id, kind, channel, actor_principal_id, reason, acted_at, recorded_at
		FROM iam.clearance_group_changes
		WHERE clearance_group_id = $1
		ORDER BY seq`
	rows, err := r.pool.Query(ctx, sql, cg.ID.String())
	if err != nil {
		return nil, mapErr(err)
	}
	defer rows.Close()

	var out []domain.ClearanceChange
	for rows.Next() {
		c := domain.ClearanceChange{ClearanceGroupID: cg.ID}
		var principal *string
		if err := rows.Scan(&c.ID, &principal, &c.Kind, &c.Channel, &c.Actor, &c.Reason, &c.ActedAt, &c.RecordedAt); err != nil {
			return nil, mapErr(err)
		}
		if principal != nil {
			c.PrincipalID = domain.PrincipalID(*principal)
		}
		out = append(out, c)
	}
	if err := rows.Err(); err != nil {
		return nil, mapErr(err)
	}
	return out, nil
}

// DelegateAgentRun implements registry.Registry.
func (r *Registry) DelegateAgentRun(ctx context.Context, parent domain.PrincipalID, spec registry.AgentRunSpec) (domain.Principal, error) {
	if err := registry.ValidateAgentRunSpec(spec, r.cfg.MaxAgentRunTTL); err != nil {
		return domain.Principal{}, err
	}

	var out domain.Principal
	err := r.inTx(ctx, func(tx pgx.Tx) error {
		now := r.cfg.Clock.Now()
		// The parent must be usable, not merely present: a principal too
		// stale to decide with is too stale to delegate from, and a
		// deprovisioned one must not be able to leave a live agent run
		// behind it.
		p, err := r.usable(ctx, tx, parent, now)
		if err != nil {
			return err
		}
		if p.Kind == domain.PrincipalKindAgentRun {
			return fmt.Errorf("%w: an agent run may not delegate a further agent run; delegation depth is captoken's object", domain.ErrInvalidPrincipal)
		}

		// The run inherits its parent's tenant and nothing else: no
		// group membership and no clearance. Delegation is a
		// discretionary act, and a discretionary act that conferred a
		// clearance would breach anti-goal A3.
		const create = `
			INSERT INTO iam.principals
				(id, tenant_id, kind, display_name, delegated_by, expires_at, synced_at, created_at)
			VALUES ($1, $2, 'agent-run', $3, $4, $5, $6, $6)
			RETURNING ` + principalColumns
		run, err := scanPrincipal(tx.QueryRow(ctx, create,
			string(domain.NewPrincipalID(r.cfg.Clock)), string(p.TenantID), spec.DisplayName,
			string(p.ID), now.Add(spec.TTL), now))
		if err != nil {
			return mapErr(err)
		}
		out = run
		return nil
	})
	if err != nil {
		return domain.Principal{}, err
	}
	return out, nil
}

// CollectExpiredAgentRuns implements registry.Registry.
//
// Memberships go with the principal through ON DELETE CASCADE; the
// clearance trail does not, because its principal_id is deliberately not a
// foreign key — the record of what a run was cleared for must outlive the
// run (see 00002_identity.sql).
func (r *Registry) CollectExpiredAgentRuns(ctx context.Context, asOf time.Time) (int, error) {
	const sql = `
		DELETE FROM iam.principals
		WHERE kind = 'agent-run' AND expires_at IS NOT NULL AND expires_at <= $1`
	tag, err := r.pool.Exec(ctx, sql, asOf)
	if err != nil {
		return 0, mapErr(err)
	}
	return int(tag.RowsAffected()), nil
}

// Deprovision implements registry.Registry.
func (r *Registry) Deprovision(ctx context.Context, p domain.PrincipalID) error {
	return r.inTx(ctx, func(tx pgx.Tx) error {
		principal, err := r.principal(ctx, tx, p)
		if err != nil {
			return err
		}
		if !principal.DeprovisionedAt.IsZero() {
			// Idempotent, and the original instant is kept: moving it
			// would rewrite when access actually stopped.
			return nil
		}

		// One statement marks the principal and cascades to its live
		// agent runs. Deprovisioning a user whose agents keep running
		// with the authority she delegated to them has not denied
		// anything, and an agent run is deliberately not subject to the
		// staleness bound, so nothing else would ever catch it. One
		// level deep, since a run may not delegate a run.
		//
		// Memberships are left in place: they stop matching at once
		// because iam.live_group_members excludes a deprovisioned
		// principal, and keeping the rows is what lets audit explain
		// what the principal had access to.
		const deprovision = `
			UPDATE iam.principals SET deprovisioned_at = $2
			WHERE deprovisioned_at IS NULL
			  AND (id = $1 OR (kind = 'agent-run' AND delegated_by = $1))`
		if _, err := tx.Exec(ctx, deprovision, string(p), r.cfg.Clock.Now()); err != nil {
			return mapErr(err)
		}
		return nil
	})
}

// inTx runs fn inside a transaction, rolling back on any error. Every
// multi-statement operation in this package goes through it, because each
// one has an invariant that spans its statements: a principal and its
// reconciled membership, a clearance membership and its trail entry, a
// deprovisioning and its cascade. A partially applied write in any of the
// three is a security defect rather than an inconsistency.
func (r *Registry) inTx(ctx context.Context, fn func(tx pgx.Tx) error) error {
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return mapErr(err)
	}
	defer func() { _ = tx.Rollback(ctx) }()

	if err := fn(tx); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return mapErr(err)
	}
	return nil
}
