// Registry is the Postgres-backed identity registry.
type Registry struct {
	pool *pgxpool.Pool
	cfg  registry.Config
}

var _ registry.Registry = (*Registry)(nil)

// New returns a Registry over pool, configured by cfg. The caller owns
// pool's lifetime and must have applied this module's migrations (see
// internal/migrate).
func New(pool *pgxpool.Pool, cfg registry.Config) (*Registry, error) {
	if pool == nil {
		return nil, fmt.Errorf("%w: pgregistry: nil connection pool", domain.ErrInvalidConfig)
	}
	normalized, err := cfg.Validate()
	if err != nil {
		return nil, err
	}
	return &Registry{pool: pool, cfg: normalized}, nil
}

// querier is the subset of pgx both *pgxpool.Pool and pgx.Tx satisfy, so
// a query reads the same whether it runs standalone or inside this
// package's transactions.
type querier interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

// principalColumns is the projection every principal read shares, in the
// order scanPrincipal expects.
const principalColumns = `id, tenant_id, kind, display_name, issuer, subject,
	delegated_by, expires_at, synced_at, deprovisioned_at, created_at`

// scanPrincipal reads one principal row.
func scanPrincipal(row pgx.Row) (domain.Principal, error) {
	var (
		p               domain.Principal
		delegatedBy     *string
		expiresAt       *time.Time
		deprovisionedAt *time.Time
	)
	err := row.Scan(&p.ID, &p.TenantID, &p.Kind, &p.DisplayName,
		&p.External.Issuer, &p.External.Subject,
		&delegatedBy, &expiresAt, &p.SyncedAt, &deprovisionedAt, &p.CreatedAt)
	if err != nil {
		return domain.Principal{}, err
	}
	if delegatedBy != nil {
		p.DelegatedBy = domain.PrincipalID(*delegatedBy)
	}
	if expiresAt != nil {
		p.ExpiresAt = *expiresAt
	}
	if deprovisionedAt != nil {
		p.DeprovisionedAt = *deprovisionedAt
	}
	return p, nil
}

// principalKey validates id before it reaches SQL and returns it as a
// bind value.
//
// The validation is not defensive tidiness: iam.ulid is a domain with a
// CHECK constraint, so a malformed id handed to Postgres raises a check
// violation rather than returning no rows — and the port documents a
// malformed id on a lookup path as ErrPrincipalNotFound, not as a
// different error. A caller able to distinguish "that id is well-formed
// but I don't have it" from "that id is nonsense" has a syntax oracle over
// the id space.
func principalKey(id domain.PrincipalID) (string, error) {
	if _, err := domain.ParsePrincipalID(string(id)); err != nil {
		return "", fmt.Errorf("%w: %s", domain.ErrPrincipalNotFound, id)
	}
	return string(id), nil
}

// groupKey validates an ordinary group id before it reaches SQL.
func groupKey(id domain.GroupID) (string, error) {
	if _, err := domain.ParseGroupID(string(id)); err != nil {
		return "", fmt.Errorf("%w: group %s", domain.ErrNotFound, id)
	}
	return string(id), nil
}

// clearanceKey validates a clearance group id before it reaches SQL.
func clearanceKey(id domain.ClearanceGroupID) (string, error) {
	if id.IsZero() {
		return "", fmt.Errorf("%w: clearance group (zero id)", domain.ErrNotFound)
	}
	if _, err := domain.ParseClearanceGroupID(id.String()); err != nil {
		return "", fmt.Errorf("%w: clearance group %s", domain.ErrNotFound, id.String())
	}
	return id.String(), nil
}

// UpsertFromClaims implements registry.Registry.
func (r *Registry) UpsertFromClaims(ctx context.Context, c registry.Claims) (domain.Principal, error) {
	if err := c.Validate(); err != nil {
		return domain.Principal{}, err
	}

	var out domain.Principal
	err := r.inTx(ctx, func(tx pgx.Tx) error {
		now := r.cfg.Clock.Now()

		// One statement covers both first sight and refresh. The id is
		// bound only for the INSERT branch: a conflict keeps the stored
		// id, which is what makes re-issuing an external identity leave
		// every grant and audit row pointing at the same principal.
		//
		// The DO UPDATE's WHERE clause is the deprovisioning guard: a
		// conflict on a deprovisioned row updates nothing and returns no
		// rows, so a fresh token for a deprovisioned subject cannot
		// revive it. Doing this in the statement rather than after a
		// read closes the window in which a concurrent deprovisioning
		// lands between the two.
		const upsert = `
			INSERT INTO iam.principals (id, tenant_id, kind, display_name, issuer, subject, synced_at, created_at)
			VALUES ($1, $2, $3, $4, $5, $6, $7, $7)
			ON CONFLICT (tenant_id, issuer, subject) WHERE issuer <> ''
			DO UPDATE SET
				kind = EXCLUDED.kind,
				display_name = EXCLUDED.display_name,
				synced_at = EXCLUDED.synced_at
			WHERE principals.deprovisioned_at IS NULL
			RETURNING ` + principalColumns

		p, err := scanPrincipal(tx.QueryRow(ctx, upsert,
			string(domain.NewPrincipalID(r.cfg.Clock)), string(c.TenantID), string(c.Kind),
			c.DisplayName, c.Subject.Issuer, c.Subject.Subject, now))
		switch {
		case err == nil:
		case errors.Is(err, pgx.ErrNoRows):
			// The only way to reach here is a conflict the DO UPDATE's
			// WHERE refused, i.e. the stored principal is
			// deprovisioned.
			return fmt.Errorf("%w: %s", domain.ErrPrincipalDeprovisioned, c.Subject)
		default:
			return mapErr(err)
		}

		if err := r.reconcileClaimGroups(ctx, tx, c.TenantID, p.ID, registry.NormalizeClaimGroups(c.Groups)); err != nil {
			return err
		}
		out = p
		return nil
	})
	if err != nil {
		return domain.Principal{}, err
	}
	return out, nil
}

// reconcileClaimGroups brings this principal's claim-sourced memberships
// to exactly want, in three statements.
//
// The middle insert uses ON CONFLICT DO NOTHING rather than DO UPDATE, so
// a membership already owned locally is not downgraded to claim-owned by
// the issuer also asserting it — otherwise a later shrinking claim set
// would remove what an operator wrote.
//
// The delete is scoped by source = 'claim', which is the whole point of
// the column: the issuer is authoritative for the memberships it sourced
// and for nothing else.
func (r *Registry) reconcileClaimGroups(ctx context.Context, q querier, tenant domain.TenantID, p domain.PrincipalID, want []string) error {
	ids := make([]string, 0, len(want))
	if len(want) > 0 {
		newIDs := make([]string, len(want))
		for i := range want {
			newIDs[i] = string(domain.NewGroupID(r.cfg.Clock))
		}
		const ensure = `
			INSERT INTO iam.groups (id, tenant_id, name)
			SELECT i.id, $1, i.name FROM unnest($2::text[], $3::text[]) AS i(id, name)
			ON CONFLICT (tenant_id, name) DO NOTHING`
		if _, err := q.Exec(ctx, ensure, string(tenant), newIDs, want); err != nil {
			return mapErr(err)
		}

		const resolve = `SELECT id FROM iam.groups WHERE tenant_id = $1 AND name = ANY($2::text[])`
		rows, err := q.Query(ctx, resolve, string(tenant), want)
		if err != nil {
			return mapErr(err)
		}
		defer rows.Close()
		for rows.Next() {
			var id string
			if err := rows.Scan(&id); err != nil {
				return mapErr(err)
			}
			ids = append(ids, id)
		}
		if err := rows.Err(); err != nil {
			return mapErr(err)
		}

		const add = `
			INSERT INTO iam.group_members (group_id, principal_id, source)
			SELECT g, $2, 'claim' FROM unnest($1::text[]) AS g
			ON CONFLICT (principal_id, group_id) DO NOTHING`
		if _, err := q.Exec(ctx, add, ids, string(p)); err != nil {
			return mapErr(err)
		}
	}

	// An empty ids array makes this remove every claim-sourced
	// membership, which is the required reading of "the token no longer
	// asserts any role".
	const prune = `
		DELETE FROM iam.group_members
		WHERE principal_id = $1 AND source = 'claim' AND group_id <> ALL($2::text[])`
	if _, err := q.Exec(ctx, prune, string(p), ids); err != nil {
		return mapErr(err)
	}
	return nil
}

// ResolveExternal implements registry.Registry.
func (r *Registry) ResolveExternal(ctx context.Context, tenant domain.TenantID, s domain.ExternalSubject) (domain.Principal, error) {
	const q = `SELECT ` + principalColumns + `
		FROM iam.principals WHERE tenant_id = $1 AND issuer = $2 AND subject = $3`
	p, err := scanPrincipal(r.pool.QueryRow(ctx, q, string(tenant), s.Issuer, s.Subject))
	if errors.Is(err, pgx.ErrNoRows) {
		return domain.Principal{}, fmt.Errorf("%w: %s", domain.ErrPrincipalNotFound, s)
	}
	if err != nil {
		return domain.Principal{}, mapErr(err)
	}
	return p, nil
}

// PrincipalByID implements registry.Registry.
func (r *Registry) PrincipalByID(ctx context.Context, id domain.PrincipalID) (domain.Principal, error) {
	return r.principal(ctx, r.pool, id)
}

func (r *Registry) principal(ctx context.Context, q querier, id domain.PrincipalID) (domain.Principal, error) {
	key, err := principalKey(id)
	if err != nil {
		return domain.Principal{}, err
	}
	const sql = `SELECT ` + principalColumns + ` FROM iam.principals WHERE id = $1`
	p, err := scanPrincipal(q.QueryRow(ctx, sql, key))
	if errors.Is(err, pgx.ErrNoRows) {
		return domain.Principal{}, fmt.Errorf("%w: %s", domain.ErrPrincipalNotFound, id)
	}
	if err != nil {
		return domain.Principal{}, mapErr(err)
	}
	return p, nil
}

// Condition implements registry.Registry.
func (r *Registry) Condition(ctx context.Context, id domain.PrincipalID, asOf time.Time) (domain.PrincipalCondition, error) {
	p, err := r.principal(ctx, r.pool, id)
	if err != nil {
		return domain.PrincipalCondition{}, err
	}
	return domain.EvaluateCondition(p, r.cfg.StalenessBound, asOf), nil
}

// usable returns the principal if it may be used at asOf, or its
// condition's error. Every principal-side membership read passes through
// it, which is what makes the staleness bound an enforcement point rather
// than a caller's responsibility.
func (r *Registry) usable(ctx context.Context, q querier, id domain.PrincipalID, asOf time.Time) (domain.Principal, error) {
	p, err := r.principal(ctx, q, id)
	if err != nil {
		return domain.Principal{}, err
	}
	if err := domain.EvaluateCondition(p, r.cfg.StalenessBound, asOf).Err(); err != nil {
		return domain.Principal{}, fmt.Errorf("%w: principal %s", err, id)
	}
	return p, nil
}

// EnsureGroup implements registry.Registry.
func (r *Registry) EnsureGroup(ctx context.Context, tenant domain.TenantID, name string) (domain.Group, error) {
	if tenant == "" || name == "" {
		return domain.Group{}, fmt.Errorf("%w: a group needs a tenant and a non-empty name", domain.ErrConflict)
	}
	const ensure = `
		INSERT INTO iam.groups (id, tenant_id, name) VALUES ($1, $2, $3)
		ON CONFLICT (tenant_id, name) DO NOTHING`
	if _, err := r.pool.Exec(ctx, ensure, string(domain.NewGroupID(r.cfg.Clock)), string(tenant), name); err != nil {
		return domain.Group{}, mapErr(err)
	}

	const read = `SELECT id, tenant_id, name, created_at FROM iam.groups WHERE tenant_id = $1 AND name = $2`
	var g domain.Group
	if err := r.pool.QueryRow(ctx, read, string(tenant), name).Scan(&g.ID, &g.TenantID, &g.Name, &g.CreatedAt); err != nil {
		return domain.Group{}, mapErr(err)
	}
	return g, nil
}

// requireGroup resolves an ordinary group id, distinguishing "this id
// names a clearance group" (ErrGroupKindMismatch — a tier confusion) from
// "this id names nothing" (ErrNotFound — a typo). An operator needs to be
// told which, and merging them would hide exactly the mistake design §8.3
// is about.
//
// One statement asks both tables, because the two namespaces are separate
// by design and no single table knows the answer.
func (r *Registry) requireGroup(ctx context.Context, q querier, id domain.GroupID) error {
	key, err := groupKey(id)
	if err != nil {
		return err
	}
	kind, err := r.idKind(ctx, q, key)
	if err != nil {
		return err
	}
	switch kind {
	case kindGroup:
		return nil
	case kindClearance:
		return fmt.Errorf("%w: %s names a clearance group, which may never be referenced as a tier-1 group", domain.ErrGroupKindMismatch, id)
	default:
		return fmt.Errorf("%w: group %s", domain.ErrNotFound, id)
	}
}

// requireClearanceGroup resolves a clearance group id, with the mirror of
// requireGroup's reasoning, and returns the group so its channel can be
// checked against the act.
func (r *Registry) requireClearanceGroup(ctx context.Context, q querier, id domain.ClearanceGroupID) (domain.ClearanceGroup, error) {
	key, err := clearanceKey(id)
	if err != nil {
		return domain.ClearanceGroup{}, err
	}
	const read = `SELECT id, tenant_id, name, channel, created_at FROM iam.clearance_groups WHERE id = $1`
	cg, err := scanClearanceGroup(q.QueryRow(ctx, read, key))
	switch {
	case err == nil:
		return cg, nil
	case !errors.Is(err, pgx.ErrNoRows):
		return domain.ClearanceGroup{}, mapErr(err)
	}

	kind, err := r.idKind(ctx, q, key)
	if err != nil {
		return domain.ClearanceGroup{}, err
	}
	if kind == kindGroup {
		return domain.ClearanceGroup{}, fmt.Errorf("%w: %s names an ordinary tier-1 group, which may never hold a clearance", domain.ErrGroupKindMismatch, key)
	}
	return domain.ClearanceGroup{}, fmt.Errorf("%w: clearance group %s", domain.ErrNotFound, key)
}

// idKind names which namespace an id belongs to.
type idKind string

const (
	kindNone      idKind = ""
	kindGroup     idKind = "group"
	kindClearance idKind = "clearance"
)

func (r *Registry) idKind(ctx context.Context, q querier, key string) (idKind, error) {
	const sql = `
		SELECT k FROM (
			SELECT 'group' AS k FROM iam.groups WHERE id = $1
			UNION ALL
			SELECT 'clearance' AS k FROM iam.clearance_groups WHERE id = $1
		) kinds LIMIT 1`
	var kind string
	err := q.QueryRow(ctx, sql, key).Scan(&kind)
	if errors.Is(err, pgx.ErrNoRows) {
		return kindNone, nil
	}
	if err != nil {
		return kindNone, mapErr(err)
	}
	return idKind(kind), nil
}

// AddGroupMember implements registry.Registry.
func (r *Registry) AddGroupMember(ctx context.Context, g domain.GroupID, p domain.PrincipalID) error {
	return r.inTx(ctx, func(tx pgx.Tx) error {
		if err := r.requireGroup(ctx, tx, g); err != nil {
			return err
		}
		principal, err := r.principal(ctx, tx, p)
		if err != nil {
			return err
		}
		if !principal.DeprovisionedAt.IsZero() {
			return fmt.Errorf("%w: %s", domain.ErrPrincipalDeprovisioned, p)
		}
		const add = `
			INSERT INTO iam.group_members (group_id, principal_id, source) VALUES ($1, $2, 'local')
			ON CONFLICT (principal_id, group_id) DO UPDATE SET source = 'local'`
		if _, err := tx.Exec(ctx, add, string(g), string(p)); err != nil {
			return mapErr(err)
		}
		return nil
	})
}

// RemoveGroupMember implements registry.Registry.
func (r *Registry) RemoveGroupMember(ctx context.Context, g domain.GroupID, p domain.PrincipalID) error {
	return r.inTx(ctx, func(tx pgx.Tx) error {
		if err := r.requireGroup(ctx, tx, g); err != nil {
			return err
		}
		key, err := principalKey(p)
		if err != nil {
			// Removing a membership for a malformed principal id is a
			// no-op, not a refusal: removal is documented idempotent,
			// and there is nothing to remove.
			return nil
		}
		const del = `DELETE FROM iam.group_members WHERE group_id = $1 AND principal_id = $2`
		if _, err := tx.Exec(ctx, del, string(g), key); err != nil {
			return mapErr(err)
		}
		return nil
	})
}

// GroupsOf implements registry.Registry.
func (r *Registry) GroupsOf(ctx context.Context, p domain.PrincipalID, asOf time.Time) ([]domain.Group, error) {
	if _, err := r.usable(ctx, r.pool, p, asOf); err != nil {
		return nil, err
	}
	const sql = `
		SELECT g.id, g.tenant_id, g.name, g.created_at
		FROM iam.group_members m
		JOIN iam.groups g ON g.id = m.group_id
		WHERE m.principal_id = $1
		ORDER BY g.name, g.id`
	rows, err := r.pool.Query(ctx, sql, string(p))
	if err != nil {
		return nil, mapErr(err)
	}
	defer rows.Close()

	var out []domain.Group
	for rows.Next() {
		var g domain.Group
		if err := rows.Scan(&g.ID, &g.TenantID, &g.Name, &g.CreatedAt); err != nil {
			return nil, mapErr(err)
		}
		out = append(out, g)
	}
	if err := rows.Err(); err != nil {
		return nil, mapErr(err)
	}
	return out, nil
}

// GroupMembers implements registry.Registry.
func (r *Registry) GroupMembers(ctx context.Context, g domain.GroupID, asOf time.Time) ([]domain.PrincipalID, error) {
	if err := r.requireGroup(ctx, r.pool, g); err != nil {
		return nil, err
	}
	const sql = `
		SELECT ` + principalColumns + `
		FROM iam.group_members m
		JOIN iam.principals p ON p.id = m.principal_id
		WHERE m.group_id = $1
		ORDER BY p.id`
	return r.usableMembers(ctx, sql, string(g), asOf)
}

// usableMembers runs a member projection and filters it to the principals
// usable at asOf.
//
// Filtering in Go, against domain.EvaluateCondition, is the deliberate
// choice described in the package doc comment: it is the same rule the
// in-memory adapter applies, from the same function, so the two cannot
// disagree about when a principal goes stale.
func (r *Registry) usableMembers(ctx context.Context, sql, key string, asOf time.Time) ([]domain.PrincipalID, error) {
	rows, err := r.pool.Query(ctx, sql, key)
	if err != nil {
		return nil, mapErr(err)
	}
	defer rows.Close()

	var out []domain.PrincipalID
	for rows.Next() {
		p, err := scanPrincipal(rows)
		if err != nil {
			return nil, mapErr(err)
		}
		if domain.EvaluateCondition(p, r.cfg.StalenessBound, asOf).Usable() {
			out = append(out, p.ID)
		}
	}
	if err := rows.Err(); err != nil {
		return nil, mapErr(err)
	}
	return out, nil
}

func scanClearanceGroup(row pgx.Row) (domain.ClearanceGroup, error) {
	var (
		id  string
		cg  domain.ClearanceGroup
		err error
	)
	if err = row.Scan(&id, &cg.TenantID, &cg.Name, &cg.Channel, &cg.CreatedAt); err != nil {
		return domain.ClearanceGroup{}, err
	}
	cg.ID, err = domain.ParseClearanceGroupID(id)
	if err != nil {
		// Only reachable if a row violating iam.ulid's CHECK exists,
		// which the schema makes impossible. Surfaced as unavailable
		// rather than silently returning a zero id.
		return domain.ClearanceGroup{}, fmt.Errorf("%w: stored clearance group id is malformed", domain.ErrUnavailable)
	}
	return cg, nil
}

// EnsureClearanceGroup implements registry.Registry.
func (r *Registry) EnsureClearanceGroup(ctx context.Context, act domain.MandatoryAct, tenant domain.TenantID, name string) (domain.ClearanceGroup, error) {
	if err := registry.RequireMandatoryAct(act); err != nil {
		return domain.ClearanceGroup{}, err
	}
	if tenant == "" || name == "" {
		return domain.ClearanceGroup{}, fmt.Errorf("%w: a clearance group needs a tenant and a non-empty name", domain.ErrConflict)
	}

	var out domain.ClearanceGroup
	err := r.inTx(ctx, func(tx pgx.Tx) error {
		const read = `SELECT id, tenant_id, name, channel, created_at
			FROM iam.clearance_groups WHERE tenant_id = $1 AND name = $2`
		cg, err := scanClearanceGroup(tx.QueryRow(ctx, read, string(tenant), name))
		switch {
		case err == nil:
			if cg.Channel != act.Channel() {
				return registry.ChannelMismatchError(cg, act)
			}
			out = cg
			return nil
		case !errors.Is(err, pgx.ErrNoRows):
			return mapErr(err)
		}

		const create = `
			INSERT INTO iam.clearance_groups (id, tenant_id, name, channel) VALUES ($1, $2, $3, $4)
			RETURNING id, tenant_id, name, channel, created_at`
		cg, err = scanClearanceGroup(tx.QueryRow(ctx, create,
			domain.NewClearanceGroupID(r.cfg.Clock).String(), string(tenant), name, string(act.Channel())))
		if err != nil {
			return mapErr(err)
		}
		if err := r.record(ctx, tx, cg.ID, "", domain.ClearanceChangeCreated, act); err != nil {
			return err
		}
		out = cg
		return nil
	})
	if err != nil {
		return domain.ClearanceGroup{}, err
	}
	return out, nil
}

