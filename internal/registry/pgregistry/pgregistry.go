// Package pgregistry is the Postgres-backed registry.Registry: the
// deployment adapter, and the one that actually has to make design §8.1's
// membership joinable. It passes iamtest.RunRegistrySuite unchanged.
//
// What this adapter adds over the in-memory one is not behaviour but
// enforcement. The in-memory adapter proves the contract; only this one
// proves the schema — that the tier separation survives a hand-written
// statement, that the clearance trail is append-only because the table
// refuses to be edited, that the agent-run shape is a constraint rather
// than a Go assertion, and that the membership probe the authorization
// predicate will embed resolves on an index. See db/migrations/00002_identity.sql
// for the schema's reasoning and pgregistry_test.go for the properties
// that only exist against real Postgres.
//
// Queries are hand-written rather than generated by sqlc, which is a
// documented departure from CONVENTIONS' default and worth the
// justification. Two reasons. The clearance-group id is a struct with an
// unexported field, deliberately, so no package outside internal/domain
// can forge or convert one (see domain.ClearanceGroupID) — mapping it
// through sqlc's column overrides would require pgx codec methods on that
// domain type, pushing a storage concern into the type whose whole point
// is that it has no reachable representation. And the writes here are
// set-reconciliation statements whose SQL is the load-bearing artifact —
// the claim reconciliation's insert-then-delete-what-is-absent, the
// deprovisioning cascade — which belong where they are read and reviewed
// rather than behind a generator.
//
// Liveness filtering is done in Go, through domain.EvaluateCondition,
// rather than in SQL. That is deliberate: the staleness bound is
// deployment configuration, and two adapters each expressing the rule in
// their own language is two chances to disagree about when a principal
// goes stale — a disagreement that would surface as one deployment
// permitting what another denies. The SQL views (iam.live_group_members)
// exist for a different caller: design §9's predicate, which runs inside
// the consumer's own statement where no Go code is available.
package pgregistry

